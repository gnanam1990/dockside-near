// Regenerates fixtures/canonical-vectors.json from the built TypeScript implementation.
// Usage: pnpm vectors   (builds first). Vectors are deterministic: keys derive from fixed seeds.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import {
  canonicalEnvelope,
  digestHexFor,
  privateKeyFromSeed,
  publicKeyOf,
  SIGNING_DOMAINS,
  sha256,
  signFor,
  toHex,
  toTypedJson,
  tradeRevisionDigest,
  tradeTermsCanonical,
  tradeTermsFromJson,
} from "../packages/core/dist/index.js";

const seed = (label) => new Uint8Array(createHash("sha256").update(`dockside-vector/${label}`).digest());
const key = (label) => privateKeyFromSeed(seed(label));
const pk = (label) => publicKeyOf(key(label));
const hexId = (prefix, label) => `${prefix}_${createHash("sha256").update(label).digest("hex").slice(0, 32)}`;

const primitives = [
  ["null", null],
  ["empty-string", ""],
  ["ascii-string", "dockside"],
  ["nfc-unicode-string", "café — 東京 🚢"],
  ["u64-zero", 0],
  ["u64-max-safe", Number.MAX_SAFE_INTEGER],
  ["u128-zero", 0n],
  ["u128-max", (1n << 128n) - 1n],
  ["u128-one-near", 10n ** 24n],
  ["bool-true", true],
  ["bool-false", false],
  ["bytes", new Uint8Array([0, 1, 2, 254, 255])],
  ["empty-list", []],
  ["nested-list", [1, "a", [true, null], 2n]],
  ["empty-struct", {}],
  ["struct-field-order", { b: 1, a: 2, B: 3, aa: 4, a_: 5, A0: 6 }],
  ["nested-struct", { outer: { z: "last", m: [{ k: 1n }], a: null } }],
];

const vectors = primitives.map(([name, value]) => {
  const env = canonicalEnvelope("dockside/test-vector", 1, value);
  return {
    name,
    domain: "dockside/test-vector",
    version: 1,
    value: toTypedJson(value),
    envelopeHex: toHex(env),
    digestHex: toHex(sha256(env)),
  };
});

const buyerOrg = hexId("org", "buyer-org");
const tradeId = hexId("trd", "trade-1");
const termsJson = {
  schemaVersion: 1,
  profileVersion: "dockside-direct-testnet-v1",
  tradeId,
  revision: 1,
  predecessorDigest: null,
  network: "near-testnet",
  escrowContractId: "dockside-escrow.testnet",
  buyer: {
    organizationId: buyerOrg,
    principalId: hexId("prn", "buyer"),
    keyVersionId: hexId("key", "buyer-1"),
    publicKey: pk("buyer"),
    accountId: "acme-buyer.testnet",
  },
  supplier: {
    organizationId: hexId("org", "supplier-org"),
    principalId: hexId("prn", "supplier"),
    keyVersionId: hexId("key", "supplier-1"),
    publicKey: pk("supplier"),
    accountId: "harbor-supplier.testnet",
  },
  asset: { kind: "NEAR_NATIVE", network: "near-testnet" },
  amountYocto: "2500000000000000000000000",
  milestone: { id: "shipment-1", description: "Container MSCU1234565 loaded — café grade A" },
  evidencePolicy: { id: "commercial-docs", revision: 1, digest: "ab".repeat(32) },
  inspector: {
    principalId: hexId("prn", "inspector"),
    keyVersionId: hexId("key", "inspector-1"),
    publicKey: pk("inspector"),
    attestationSchema: "dockside/inspection-attestation@1",
  },
  manifestAttestor: {
    enrollmentId: hexId("svc", "attestor"),
    serviceId: "manifest-attestor",
    keyVersion: 1,
    publicKey: pk("attestor"),
    capability: "MANIFEST_ATTEST",
    scope: {
      organizationId: buyerOrg,
      tradeId: null,
      evidencePolicyId: "commercial-docs",
      evidencePolicyRevision: 1,
    },
    attestationSchema: "dockside/manifest-attestation@1",
  },
  policySetter: {
    enrollmentId: hexId("svc", "policy"),
    serviceId: "deterministic-policy",
    keyVersion: 1,
    publicKey: pk("policy"),
    capability: "DETERMINISTIC_POLICY_SET",
    scope: {
      organizationId: buyerOrg,
      tradeId,
      evidencePolicyId: "commercial-docs",
      evidencePolicyRevision: 1,
    },
    attestationSchema: "dockside/hold-set@1",
  },
  riskResolver: {
    principalId: hexId("prn", "risk"),
    keyVersionId: hexId("key", "risk-1"),
    publicKey: pk("risk"),
  },
  payout: { network: "near-testnet", recipientType: "NEAR_ACCOUNT", destination: "harbor-supplier.testnet" },
  refundPolicy: { id: "dockside-refund-v1", revision: 1 },
  delayPolicy: { destinationChangeDelayMs: 86400000 },
  expiresAt: 1900000000000,
};
const terms = tradeTermsFromJson(termsJson);
const canonical = tradeTermsCanonical(terms);
const d = SIGNING_DOMAINS.TRADE_REVISION;
const env = canonicalEnvelope(d.domain, d.version, canonical);
vectors.push({
  name: "trade-revision-v1",
  domain: d.domain,
  version: d.version,
  value: toTypedJson(canonical),
  envelopeHex: toHex(env),
  digestHex: toHex(sha256(env)),
});

const out = {
  format: "dockside-canonical-encoding-v1",
  note: "Generated by scripts/generate-vectors.mjs. Shared by TypeScript (packages/core) and Rust (contract/crates/dockside-canonical) tests.",
  vectors,
  tradeTerms: { json: termsJson, digestHex: tradeRevisionDigest(terms) },
  signatures: [
    {
      name: "buyer-signs-trade-revision",
      purpose: "TRADE_REVISION",
      domain: d.domain,
      version: d.version,
      publicKey: pk("buyer"),
      digestHex: digestHexFor("TRADE_REVISION", canonical),
      signature: signFor(key("buyer"), "TRADE_REVISION", canonical),
    },
  ],
};
writeFileSync(
  new URL("../fixtures/canonical-vectors.json", import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`,
);
console.log(`wrote ${vectors.length} vectors`);
